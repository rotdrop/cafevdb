import type { App } from 'vue';
import type { PersonalSettingsConfig } from '../types/personal-settings.d.ts';

import Tooltip from '@rotdrop/nextcloud-vue-components/lib/directives/Tooltip';
import { createPinia } from 'pinia';
import { createApp } from 'vue';
import PersonalSettings from '../components/PersonalSettings.vue';
import { appName } from '../config.ts';
import { mixin as globalMixin } from '../mixins/global-mixin.ts';
import $ from './jquery.ts';

import 'core-js/actual';

export interface MountCallbacks {
  onEncryptionKeySet?: () => void|Promise<void>;
}

let app: App|undefined;
let mountPoint: HTMLElement|undefined;

/**
 * Tear down the current instance, if any. Needed before the DOM
 * holding the mount-point is replaced or removed.
 */
export const unmountPersonalSettings = () => {
  app?.unmount();
  app = undefined;
  mountPoint = undefined;
};

/**
 * Mount the personal-settings component into the given element. The
 * configuration is taken from its data-config attribute. Mounting the
 * same element repeatedly is a no-op.
 *
 * @param element The mount-point generated by templates/settings/personal-settings.php.
 *
 * @param callbacks Callbacks for events emitted by the component.
 */
export const mountPersonalSettings = (element: JQuery|HTMLElement, callbacks: MountCallbacks = {}) => {
  const target = $(element).get(0);
  if (!target) {
    return;
  }
  if (target === mountPoint) {
    return;
  }
  unmountPersonalSettings();

  const config: PersonalSettingsConfig = JSON.parse(target.dataset.config || '{}');

  app = createApp(PersonalSettings, {
    config,
    onEncryptionKeySet: () => callbacks.onEncryptionKeySet?.(),
  });
  app.directive('tooltip', Tooltip);
  app.provide('appId', appName);
  app.mixin(globalMixin);
  app.use(createPinia());
  app.mount(target);
  mountPoint = target;
};
